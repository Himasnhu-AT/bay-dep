//! **The font resolution gate**: a `(family, weight)` that does not shape as asked is refused.
//!
//! cosmic-text does not snap to the nearest weight. It drops the family and shapes in something
//! else, and every frame still comes out, so nothing downstream can tell. Measured on this
//! machine and reproduced by the tests below: `Avenir` at 700 shapes in **Menlo Bold** — a
//! terminal face — and `Baskerville` at 900 in **Apple SD Gothic Neo Heavy**, a Korean UI face.
//! The obvious typographic improvement, "extreme weight contrast, 300 against 900", therefore
//! ships a video set in two faces nobody chose while passing every other check bay has.
//!
//! The gate is not a threshold and cannot be tuned: it shapes one glyph, reads the face id off
//! the resulting `LayoutGlyph`, and compares. It is only ever satisfiable by naming a face that
//! is really installed.
//!
//! `TABLE` is generated from the machine, not written by hand — regenerate it with
//! `BAY_WRITE_FONT_TABLE=1 cargo test -p bay-mcp --test font_resolution`.

use bay_mcp::{Studio, tools};
use bay_project::builtin_kits;
use serde_json::{Value, json};

/// The generated `family → {resolvable weights, metric class, cap/em}` table.
const TABLE: &str = include_str!("fixtures/font-resolution.md");
const TABLE_PATH: &str = "tests/fixtures/font-resolution.md";

/// The font set the kits were chosen against. Where it is missing this is not a Mac with the
/// standard faces, and the test says so rather than failing for reasons outside the repository.
fn have_system_fonts(raster: &mut bay_text::TextRaster) -> bool {
    raster.has_family("Helvetica Neue") && raster.has_family("Menlo")
}

/// Every family any built-in kit names, once each, sorted.
fn kit_families() -> Vec<String> {
    let mut names: Vec<String> = builtin_kits()
        .iter()
        .flat_map(|kit| {
            [
                kit.faces.display.family.clone(),
                kit.faces.body.family.clone(),
                kit.faces.mono.family.clone(),
            ]
        })
        .collect();
    names.sort();
    names.dedup();
    names
}

fn generate_table(raster: &mut bay_text::TextRaster) -> String {
    let mut out = String::from(
        "<!-- Generated by `BAY_WRITE_FONT_TABLE=1 cargo test -p bay-mcp --test \
         font_resolution`. -->\n\n\
         | family | resolvable weights | metric class | cap/em |\n\
         | --- | --- | --- | --- |\n",
    );
    for family in kit_families() {
        let weights = raster.resolvable_weights(&family);
        let face = weights
            .first()
            .and_then(|weight| raster.resolve_face(&family, *weight));
        out.push_str(&format!(
            "| {family} | {} | {} | {:.3} |\n",
            weights
                .iter()
                .map(|w| w.to_string())
                .collect::<Vec<_>>()
                .join(" "),
            face.as_ref().map(|f| f.metric_class()).unwrap_or("-"),
            face.as_ref().and_then(|f| f.cap_per_em).unwrap_or(0.0),
        ));
    }
    out
}

/// One row of the checked-in table.
struct Row {
    family: String,
    weights: Vec<u16>,
    metric_class: String,
    cap_per_em: f32,
}

fn table_rows() -> Vec<Row> {
    TABLE
        .lines()
        .filter(|line| {
            line.starts_with("| ") && !line.contains("---") && !line.contains("family |")
        })
        .map(|line| {
            let cells: Vec<&str> = line.trim_matches('|').split('|').map(str::trim).collect();
            Row {
                family: cells[0].to_string(),
                weights: cells[1]
                    .split_whitespace()
                    .filter_map(|w| w.parse().ok())
                    .collect(),
                metric_class: cells[2].to_string(),
                cap_per_em: cells[3].parse().unwrap_or(0.0),
            }
        })
        .collect()
}

/// **The claim §1.1 exists to make.** Every one of the twelve built-in kits names three faces
/// that shape in the family and at the weight they say — a kit that does not is a shipped bug,
/// because every element drawn with it renders in a substitute.
#[test]
fn every_builtin_kit_shapes_in_the_family_it_names() {
    let mut raster = bay_text::TextRaster::new();
    if !have_system_fonts(&mut raster) {
        eprintln!(
            "skipping: this machine does not have the macOS system font set (no Helvetica Neue \
             or no Menlo), so the kits cannot be checked against it"
        );
        return;
    }
    let mut failures: Vec<String> = Vec::new();
    for kit in builtin_kits() {
        for (slot, face) in [
            ("display", &kit.faces.display),
            ("body", &kit.faces.body),
            ("mono", &kit.faces.mono),
        ] {
            match raster.resolve_face(&face.family, face.weight) {
                Some(resolved) if resolved.is(&face.family) && resolved.weight == face.weight => {}
                Some(resolved) => failures.push(format!(
                    "{}/{slot}: {:?} at weight {} shapes as {:?} at weight {} — the whole kit \
                     would render in a face nobody chose",
                    kit.id, face.family, face.weight, resolved.family, resolved.weight
                )),
                None => failures.push(format!(
                    "{}/{slot}: nothing at all shaped for {:?}",
                    kit.id, face.family
                )),
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} of the built-in kits do not resolve here:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

/// The measured substitutions, asserted as facts about this machine so a change in cosmic-text
/// or in the system font set shows up here rather than in a rendered frame.
#[test]
fn a_missing_weight_drops_the_family_rather_than_snapping() {
    let mut raster = bay_text::TextRaster::new();
    if !have_system_fonts(&mut raster) {
        eprintln!("skipping: no macOS system font set on this machine");
        return;
    }
    assert!(
        raster.resolves("Avenir", 400),
        "Avenir at its own weight must resolve"
    );
    let heavy = raster
        .resolve_face("Avenir", 700)
        .expect("something always shapes");
    assert!(
        !heavy.is("Avenir"),
        "Avenir has no 700 cut; if this now resolves the substitution story has changed: {heavy:?}"
    );
    assert!(
        heavy.monospaced,
        "the measured substitute is Menlo Bold, a monospace terminal face: {heavy:?}"
    );

    let black = raster
        .resolve_face("Baskerville", 900)
        .expect("something always shapes");
    assert!(
        !black.is("Baskerville"),
        "Baskerville has no 900 cut: {black:?}"
    );
}

/// The gate, through the tool surface: a kit that came off disk naming a face this machine does
/// not have must refuse the placement, not draw it in a substitute.
#[test]
fn add_text_refuses_a_kit_whose_face_would_be_substituted() {
    let (mut studio, root) = scratch_studio("resolution");
    let mut kit = bay_project::builtin_kit("swiss").unwrap().clone();
    kit.id = "hand-written".into();
    // The exact pair from the plan: Avenir has no 700 cut, so this renders in Menlo Bold.
    kit.faces.display = bay_project::TypeFace::new("Avenir", 700);

    let mut project = bay_project::Project::empty(
        "resolution",
        "Resolution",
        bay_project::CanvasSize {
            width: 1080,
            height: 1920,
        },
        bay_project::Fps {
            numerator: 30,
            denominator: 1,
        },
        "#000000",
    );
    project.settings.kit = Some(kit);
    let path = root.join("bad-kit.json");
    std::fs::write(&path, serde_json::to_string(&project).unwrap()).unwrap();
    call(
        &mut studio,
        "project_load",
        json!({ "path": path.to_string_lossy() }),
    );

    let error = call_err(
        &mut studio,
        "add_text",
        json!({ "role": "headline", "start": 0, "duration": 2, "content": "Hook" }),
    );
    assert!(error.contains("Avenir"), "{error}");
    assert!(
        error.contains("Menlo"),
        "the message names what would actually be drawn: {error}"
    );
    assert!(
        error.contains("fonts_check") || error.contains("style_pick"),
        "…and what to do about it: {error}"
    );

    // A role drawn with a face the kit got right is unaffected — the gate is per face, not a
    // blanket refusal of the project.
    call(
        &mut studio,
        "add_text",
        json!({ "role": "label", "start": 0, "duration": 2, "content": "note" }),
    );
}

/// `fonts_check` answers the question that matters. "Is Avenir installed" is yes and useless;
/// "which weights does Avenir have" is what stops a kit naming one it does not.
#[test]
fn fonts_check_reports_weights_not_just_presence() {
    let (mut studio, _root) = scratch_studio("fonts-check");
    let mut raster = bay_text::TextRaster::new();
    if !have_system_fonts(&mut raster) {
        eprintln!("skipping: no macOS system font set on this machine");
        return;
    }
    let body = call(
        &mut studio,
        "fonts_check",
        json!({ "families": ["Avenir", "Menlo", "Definitely Not A Real Typeface 9000"] }),
    );
    let faces = body["faces"].as_array().expect("a row per family");
    assert_eq!(faces.len(), 3, "{body}");

    let avenir = faces.iter().find(|f| f["family"] == "Avenir").unwrap();
    let weights: Vec<u64> = avenir["weights"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|w| w.as_u64())
        .collect();
    assert!(weights.contains(&400), "{avenir}");
    assert!(
        !weights.contains(&700),
        "Avenir has no 700 cut and must not be reported as having one: {avenir}"
    );
    assert_eq!(avenir["metricClass"], "proportional", "{avenir}");
    assert!(
        avenir["capPerEm"].as_f64().unwrap() > 0.5,
        "cap height is measured off the face: {avenir}"
    );

    let menlo = faces.iter().find(|f| f["family"] == "Menlo").unwrap();
    assert_eq!(menlo["metricClass"], "monospace", "{menlo}");

    assert_eq!(
        body["missing"].as_array().map(|m| m.len()),
        Some(1),
        "an invented family is missing, not available: {body}"
    );
}

/// The generated table, checked back against the machine that generated it.
///
/// Rows for families this machine does not have are skipped rather than failed — the table is a
/// record of what a standard macOS install offers, and a Linux CI box is not one.
#[test]
fn the_generated_table_still_describes_this_machine() {
    let mut raster = bay_text::TextRaster::new();
    if std::env::var("BAY_WRITE_FONT_TABLE").is_ok() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(TABLE_PATH);
        std::fs::write(&path, generate_table(&mut raster)).expect("write the table");
        eprintln!("wrote {}", path.display());
        return;
    }
    if !have_system_fonts(&mut raster) {
        eprintln!("skipping: no macOS system font set on this machine");
        return;
    }
    let rows = table_rows();
    assert_eq!(
        rows.len(),
        kit_families().len(),
        "the table has a row per family the kits name; regenerate it with BAY_WRITE_FONT_TABLE=1"
    );
    let mut problems: Vec<String> = Vec::new();
    for row in rows {
        if !raster.has_family(&row.family) {
            eprintln!("skipping {}: not installed here", row.family);
            continue;
        }
        let weights = raster.resolvable_weights(&row.family);
        if weights != row.weights {
            problems.push(format!(
                "{}: the table says weights {:?}, this machine resolves {:?}",
                row.family, row.weights, weights
            ));
        }
        let Some(face) = weights
            .first()
            .and_then(|weight| raster.resolve_face(&row.family, *weight))
        else {
            continue;
        };
        if face.metric_class() != row.metric_class {
            problems.push(format!(
                "{}: the table says {}, the face says {}",
                row.family,
                row.metric_class,
                face.metric_class()
            ));
        }
        if let Some(cap) = face.cap_per_em
            && (cap - row.cap_per_em).abs() > 0.002
        {
            problems.push(format!(
                "{}: the table says cap/em {:.3}, the face measures {cap:.3}",
                row.family, row.cap_per_em
            ));
        }
    }
    assert!(
        problems.is_empty(),
        "regenerate with BAY_WRITE_FONT_TABLE=1 if this machine is right:\n{}",
        problems.join("\n")
    );
}

