/**
 * Writes the two tool registries from the files that define the tools.
 *
 * Every tool used to be registered by hand in two lists: its spec appended to `TOOLS` in
 * `shared/mcp.ts`, and its handler added to `HANDLERS` in `renderer/mcp/index.ts`. Those were
 * the two most-edited files in the tree, and every agent adding a tool appended to the same
 * spot in both, which is where parallel branches collided. Now a tool is a file in
 * `src/shared/tools/`, a handler is an entry in its own module's `handlers`, and the lists are
 * generated. Two new tools are two new files and two different lines in each generated index.
 *
 * The indexes are checked in, not produced at build time, for two reasons. A plain import is a
 * static edge that `graft`, grep and `committed-imports.ts` can all follow; a build-time glob
 * (`import.meta.glob`) is none of those, and it is Vite-only, so `node --test` — which loads
 * `shared/` without Vite — would see no tools at all and pass. And a checked-in file can be
 * checked: `tool-registry.test.ts` regenerates both in memory and fails, naming the command,
 * when either differs from what is on disk.
 *
 * Pure over a listing and a reader, so the tests can feed it specimens. `script/gen-tools.mjs`
 * is the command that writes the files.
 */

export interface SourceFile {
  /** File name within its directory, e.g. `list-projects.ts`. */
  name: string
  source: string
}

export const GENERATED_BANNER =
  '// GENERATED by `pnpm gen:tools` from the files beside it. Do not edit by hand.'

/** `list-projects.ts` → `listProjects`. */
function identifier(fileName: string): string {
  return fileName
    .replace(/\.tsx?$/, '')
    .replace(/[-_.]+([a-z0-9])/gi, (_, c: string) => c.toUpperCase())
}

const ORDER = /^export const order = (\d+)\s*$/m
const TOOL = /^export const tool: ToolSpec = \{/m
const TOOL_NAME = /^\s+name: '([a-z_]+)'/m

/** The catalog files: every `.ts` in `src/shared/tools/` except the index and its helpers. */
export function isToolFile(name: string): boolean {
  return /\.ts$/.test(name) && !/\.test\.ts$/.test(name) && !['index.ts', 'spec.ts', 'fields.ts'].includes(name)
}

/**
 * `src/shared/tools/index.ts`: `TOOLS`, in catalog order.
 *
 * The order is published — it is the order of the MCP manifest and of each section of the
 * generated tool reference — so each file says where it goes with `export const order = N`
 * rather than the list being alphabetical. Ties break by file name, so two branches that pick
 * the same number still produce one deterministic list.
 */
export function catalogIndex(files: SourceFile[]): string {
  const faults: string[] = []
  const entries: { file: string; id: string; order: number; tool: string }[] = []
  for (const file of files.filter((f) => isToolFile(f.name))) {
    const order = ORDER.exec(file.source)?.[1]
    const tool = TOOL_NAME.exec(file.source.slice(file.source.search(TOOL)))?.[1]
    if (order === undefined) faults.push(`${file.name} has no \`export const order = <number>\``)
    if (!TOOL.test(file.source) || tool === undefined) {
      faults.push(`${file.name} has no \`export const tool: ToolSpec = { name: '…', … }\``)
    }
    if (order === undefined || tool === undefined) continue
    entries.push({ file: file.name, id: identifier(file.name), order: Number(order), tool })
  }
  const byName = new Map<string, string>()
  for (const entry of entries) {
    const other = byName.get(entry.tool)
    if (other) faults.push(`${other} and ${entry.file} both define the tool '${entry.tool}'`)
    byName.set(entry.tool, entry.file)
  }
  if (faults.length > 0) throw new Error(`Cannot generate the tool catalog: ${faults.join('; ')}.`)

  const imports = [...entries]
    .sort((a, b) => a.file.localeCompare(b.file))
    .map((e) => `import { tool as ${e.id} } from './${e.file.replace(/\.ts$/, '')}'`)
  const listed = [...entries]
    .sort((a, b) => a.order - b.order || a.file.localeCompare(b.file))
    .map((e) => `  ${e.id},`)
  return [
    GENERATED_BANNER,
    '// A tool is a file here exporting `order` and `tool`; add one, then run `pnpm gen:tools`.',
    '',
    "import type { ToolSpec } from './spec'",
    ...imports,
    '',
    '/** Every tool bay serves, in the order the manifest lists them. */',
    'export const TOOLS: ToolSpec[] = [',
    ...listed,
    ']',
    ''
  ].join('\n')
}

const HANDLERS = /^export const handlers: Handlers = \{/m

/**
 * `src/renderer/src/mcp/registry.ts`: every executor module's `handlers`, merged.
 *
 * A module takes part by exporting `handlers: Handlers`. The groups are also exported one by
 * one, so a test can prove no tool is claimed twice — a spread would silently let the later
 * module win.
 */
export function handlerIndex(files: SourceFile[]): string {
  const modules = files
    .filter((f) => /\.ts$/.test(f.name) && !/\.test\.ts$/.test(f.name) && f.name !== 'registry.ts')
    .filter((f) => HANDLERS.test(f.source))
    .map((f) => ({ file: f.name, id: `${identifier(f.name)}Handlers` }))
    .sort((a, b) => a.file.localeCompare(b.file))
  return [
    GENERATED_BANNER,
    '// A module takes part by exporting `handlers: Handlers`; then run `pnpm gen:tools`.',
    '',
    "import type { Handlers } from './helpers'",
    ...modules.map((m) => `import { handlers as ${m.id} } from './${m.file.replace(/\.ts$/, '')}'`),
    '',
    '/** Each module’s handlers, separately, so a tool claimed twice can be found. */',
    'export const HANDLER_GROUPS: Record<string, Handlers> = {',
    ...modules.map((m) => `  '${m.file.replace(/\.ts$/, '')}': ${m.id},`),
    '}',
    '',
    '/** Tool name → handler, for the dispatcher. */',
    'export const HANDLERS: Handlers = {',
    ...modules.map((m) => `  ...${m.id},`),
    '}',
    ''
  ].join('\n')
}
