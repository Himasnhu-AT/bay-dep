/**
 * `src/shared/motion/` as one classic script: the text of `bay-motion.js`.
 *
 * A composition page cannot import modules from bay — it may load only files in its own folder —
 * so the library reaches it as a file, and that file must not be a second, hand-kept copy of the
 * moves. This builds it from the TypeScript itself: each module reachable from the entry is
 * compiled (Sucrase: types removed, imports turned into `require`), wrapped in a function, and
 * the lot is tied together by a few lines of loader that leave one global, `BM`.
 *
 * The result is checked in (`src/main/html/motion-script.generated.ts`, `pnpm gen:motion`)
 * because main needs it as a string at run time and neither Vite nor Node's test runner would
 * otherwise produce it. `src/main/html/motion-script.test.ts` fails when the checked-in text is
 * not what this function makes of the sources on disk, and separately runs the script and
 * compares every move's output with the TypeScript's.
 *
 * Pure over a reader, like `tool-registry.ts`, so the tests can feed it specimens.
 */

import { transform } from 'sucrase'
import { MOTION_BANNER, MOTION_GLOBAL } from './motion-file'

/** Module ids are paths under `src/shared`, without an extension. */
const ENTRY = 'motion/index'

function resolveFrom(importer: string, specifier: string): string {
  const parts = importer.split('/').slice(0, -1)
  for (const part of specifier.split('/')) {
    if (part === '.' || part === '') continue
    if (part === '..') {
      if (parts.length === 0) throw new Error(`src/shared/${importer}.ts imports "${specifier}", which is outside src/shared`)
      parts.pop()
    } else {
      parts.push(part)
    }
  }
  return parts.join('/')
}

/**
 * The script. `read(id)` returns the source of `src/shared/<id>.ts`, or null when there is no
 * such file. Throws, naming the import, if a module reaches for anything but a relative file —
 * a package or a Node builtin cannot be put in a composition's folder.
 */
export function motionScript(read: (id: string) => string | null, entry = ENTRY): string {
  const order: string[] = []
  const compiled = new Map<string, { code: string; imports: Record<string, string> }>()

  const visit = (id: string, importer: string | null): void => {
    if (compiled.has(id)) return
    const source = read(id)
    if (source === null) {
      throw new Error(`${importer ?? 'the motion bundle'} imports "${id}", and src/shared/${id}.ts does not exist`)
    }
    const code = transform(source, { transforms: ['typescript', 'imports'], production: true }).code
    const imports: Record<string, string> = {}
    // Reserved before recursing, so two modules importing each other terminate.
    compiled.set(id, { code, imports })
    for (const match of code.matchAll(/\brequire\(\s*(['"])([^'"]+)\1\s*\)/g)) {
      const specifier = match[2]!
      if (!specifier.startsWith('.')) {
        throw new Error(
          `src/shared/${id}.ts imports "${specifier}". The move library is written into a composition's ` +
            `folder as one script, so it may import only other files under src/shared, by relative path.`
        )
      }
      const target = resolveFrom(id, specifier)
      imports[specifier] = target
      visit(target, `src/shared/${id}.ts`)
    }
    order.push(id)
  }
  visit(entry, null)

  const lines = [
    `${MOTION_BANNER} — bay's move library, as the global ${MOTION_GLOBAL}. GENERATED by bay from its own source: do not edit, bay rewrites this file. */`,
    `var ${MOTION_GLOBAL} = (function () {`,
    'var defs = {}'
  ]
  for (const id of order) {
    const { code, imports } = compiled.get(id)!
    lines.push(`defs[${JSON.stringify(id)}] = [${JSON.stringify(imports)}, function (exports, require, module) {`)
    lines.push(code.trimEnd())
    lines.push('}]')
  }
  lines.push(
    'var loaded = {}',
    'function load(id) {',
    '  if (loaded[id]) return loaded[id].exports',
    '  var module = (loaded[id] = { exports: {} })',
    '  var def = defs[id]',
    '  def[1](module.exports, function (name) { return load(def[0][name]) }, module)',
    '  return module.exports',
    '}',
    `return load(${JSON.stringify(entry)})`,
    '})()',
    ''
  )
  return lines.join('\n')
}

/** The checked-in module that carries the script, as source text. One array element per line, so a diff is readable. */
export function motionScriptModule(script: string): string {
  return [
    '// GENERATED by `pnpm gen:motion` from src/shared/motion. Do not edit by hand.',
    '// What this is and why it is checked in: src/shared/motion-bundle.ts.',
    '',
    "/** The text of `bay-motion.js`: bay's move library as one classic script defining `BM`. */",
    'export const MOTION_SCRIPT: string = [',
    ...script.split('\n').map((line) => `  ${JSON.stringify(line)},`),
    "].join('\\n')",
    ''
  ].join('\n')
}
